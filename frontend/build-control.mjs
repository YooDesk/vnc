// 将权威 control-v2 Schema 编译为无 eval 的浏览器校验器；产物必须随协议一起复核。
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { build } from 'esbuild';
import { format, resolveConfig } from 'prettier';

const root = new URL('../', import.meta.url);
const input = await readFile(new URL('protocol/control-v2.schema.json', root), 'utf8');
// AJV 的 strictRequired 要求 required 与 properties 在同一子句声明，
// control-v2 依 JSON Schema 2020 在祖先定义字段、在 then 中要求出现。
// 仅在编译副本中重复已有的相同字段约束；不改原定义、不关闭任何校验。
function localRequiredDefinitions(value, inherited = {}) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) return value;
  const node = structuredClone(value);
  const known = { ...inherited };
  for (const [name, definition] of Object.entries(node.properties ?? {}))
    known[name] =
      definition && typeof definition === 'object'
        ? { ...inherited[name], ...definition }
        : definition;
  for (const name of node.required ?? []) {
    if (!Object.hasOwn(node.properties ?? {}, name) && Object.hasOwn(known, name)) {
      if (node.additionalProperties === false)
        throw new Error('Cannot duplicate inherited property under additionalProperties=false');
      node.properties ??= {};
      node.properties[name] = structuredClone(known[name]);
    }
  }
  for (const key of ['if', 'then', 'else', 'not'])
    if (node[key]) node[key] = localRequiredDefinitions(node[key], known);
  for (const key of ['allOf', 'anyOf', 'oneOf'])
    if (node[key]) node[key] = node[key].map((child) => localRequiredDefinitions(child, known));
  for (const key of ['properties', '$defs', 'patternProperties'])
    if (node[key])
      for (const name of Object.keys(node[key])) {
        const child = node[key][name];
        if (
          key === 'properties' &&
          child &&
          typeof child === 'object' &&
          child.type === undefined &&
          inherited[name]?.type !== undefined
        )
          child.type = structuredClone(inherited[name].type);
        node[key][name] = localRequiredDefinitions(child);
      }
  for (const key of ['items', 'contains', 'additionalProperties'])
    if (node[key] && typeof node[key] === 'object') node[key] = localRequiredDefinitions(node[key]);
  return node;
}
const ajv = new Ajv2020({
  strict: true,
  allErrors: false,
  coerceTypes: false,
  removeAdditional: false,
  code: { source: true },
});
addFormats(ajv);
const validate = ajv.compile(localRequiredDefinitions(JSON.parse(input)));
const code = standaloneCode(ajv, validate);
const compiled = await build({
  stdin: {
    contents: code,
    resolveDir: fileURLToPath(new URL('.', import.meta.url)),
    sourcefile: 'control-schema.cjs',
    loader: 'js',
  },
  write: false,
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'chrome120',
});
const digest = createHash('sha256').update(input).digest('hex');
const header =
  '// Generated by build-control.mjs from protocol/control-v2.schema.json. Do not edit.\n';
const options = await resolveConfig(fileURLToPath(new URL('.prettierrc.json', import.meta.url)));
const source = await format(
  header + compiled.outputFiles[0].text + `\nexport const schemaSHA256 = '${digest}';\n`,
  { ...options, parser: 'babel' },
);
const outputs = [
  [new URL('packages/transport/control-schema.js', import.meta.url), source],
  [new URL('gateway/internal/control/schema.json', root), input],
];
for (const [path, expected] of outputs) {
  if (process.argv.includes('--write')) await writeFile(path, expected, 'utf8');
  else if ((await readFile(path, 'utf8')) !== expected)
    throw new Error(`Protocol runtime snapshot out of date: ${fileURLToPath(path)}`);
}
